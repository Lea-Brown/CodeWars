/**
 * 7 kyu
 * Reverse list
 * https://www.codewars.com/kata/57a04da9e298a7ee43000111/javascript
 *
 * Reverses the order of the elements in an array.
 *
 * @param {Array<*>} arr - The array to reverse.
 * @returns {Array<*>} The reversed array.
 *
 * @example
 * reverseList([1, 2, 3, 4]);
 * // Returns: [4, 3, 2, 1]
 *
 * @example
 * reverseList(['a', 'b', 'c']);
 * // Returns: ['c', 'b', 'a']
 *
 * @example
 * reverseList([10]);
 * // Returns: [10]
 */
const reverseList = (arr) => arr.reverse();
